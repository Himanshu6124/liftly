// Renders Liftly's app icon from one geometry: a loaded barbell (side view) in competition-plate
// colors on graphite, the "Calibrated plates" palette. Writes the iOS 1024 px PNG and the Android
// adaptive-icon foreground + monochrome vectors. Run from the repo root: swift tools/icon/render_icon.swift
import CoreGraphics
import ImageIO
import Foundation

struct Shape { let x: Double; let y: Double; let w: Double; let h: Double; let r: Double; let color: String }

// Design space: 1024 × 1024, barbell centred. Plates from the collar outward: red 25, blue 20, yellow 15.
let graphite = "#16181C"
let bar = "#E9EBEE"
func makeShapes() -> [Shape] {
    var s: [Shape] = [Shape(x: 96, y: 490, w: 832, h: 44, r: 22, color: bar)] // bar + sleeves
    // From the collar outward: offset from the collar's inner edge, width, height, color.
    let plates: [[String]] = [
        ["0", "26", "150", bar],          // collar
        ["36", "62", "560", "#E0262C"],   // 25 kg red
        ["108", "62", "470", "#2463E8"],  // 20 kg blue
        ["180", "62", "380", "#F2C12E"],  // 15 kg yellow
    ]
    let innerLeft = 360.0 // collar's inner edge on the left; mirrored on the right
    for p in plates {
        let dx = Double(p[0])!, w = Double(p[1])!, h = Double(p[2])!
        let y = 512 - h / 2, r = min(20, w / 2)
        s.append(Shape(x: innerLeft - dx - w, y: y, w: w, h: h, r: r, color: p[3]))
        s.append(Shape(x: 1024 - innerLeft + dx, y: y, w: w, h: h, r: r, color: p[3]))
    }
    return s
}
let shapes = makeShapes()

func cgColor(_ hex: String) -> CGColor {
    let v = Int(hex.dropFirst(), radix: 16)!
    return CGColor(srgbRed: CGFloat((v >> 16) & 0xFF) / 255, green: CGFloat((v >> 8) & 0xFF) / 255,
                   blue: CGFloat(v & 0xFF) / 255, alpha: 1)
}

// iOS: full-bleed, opaque 1024 PNG (the system applies the rounded mask; App Store icons may not
// have alpha). Content at 94 % keeps it clear of the corners.
func renderPNG(to path: String) {
    let size = 1024
    let ctx = CGContext(data: nil, width: size, height: size, bitsPerComponent: 8, bytesPerRow: 0,
                        space: CGColorSpace(name: CGColorSpace.sRGB)!,
                        bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue)!
    ctx.setFillColor(cgColor(graphite))
    ctx.fill(CGRect(x: 0, y: 0, width: size, height: size))
    let scale = 0.94, offset = 512 * (1 - scale)
    for s in shapes {
        ctx.setFillColor(cgColor(s.color))
        // Core Graphics' origin is bottom-left; the design's is top-left.
        let rect = CGRect(x: offset + s.x * scale, y: Double(size) - offset - (s.y + s.h) * scale,
                          width: s.w * scale, height: s.h * scale)
        ctx.addPath(CGPath(roundedRect: rect, cornerWidth: s.r * scale, cornerHeight: s.r * scale, transform: nil))
        ctx.fillPath()
    }
    let dest = CGImageDestinationCreateWithURL(URL(fileURLWithPath: path) as CFURL, "public.png" as CFString, 1, nil)!
    CGImageDestinationAddImage(dest, ctx.makeImage()!, nil)
    CGImageDestinationFinalize(dest)
}

// Android: 108 dp adaptive foreground; everything must sit inside the 66 dp safe circle.
func vector(monochrome: Bool) -> String {
    let scale = 62.0 / 832.0, offset = 54 - 512 * scale
    func f(_ v: Double) -> String { String(format: "%.2f", v) }
    let paths = shapes.map { s -> String in
        let x = offset + s.x * scale, y = offset + s.y * scale, w = s.w * scale, h = s.h * scale, r = s.r * scale
        let d = "M\(f(x + r)),\(f(y))h\(f(w - 2 * r))a\(f(r)),\(f(r)) 0,0 1,\(f(r)),\(f(r))v\(f(h - 2 * r))" +
            "a\(f(r)),\(f(r)) 0,0 1,-\(f(r)),\(f(r))h-\(f(w - 2 * r))a\(f(r)),\(f(r)) 0,0 1,-\(f(r)),-\(f(r))" +
            "v-\(f(h - 2 * r))a\(f(r)),\(f(r)) 0,0 1,\(f(r)),-\(f(r))z"
        return "    <path\n        android:fillColor=\"\(monochrome ? "#FFFFFFFF" : s.color)\"\n        android:pathData=\"\(d)\" />"
    }
    var out = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
    out += "<!-- Generated by tools/icon/render_icon.swift; edit the geometry there. -->\n"
    out += "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n"
    out += "    android:width=\"108dp\"\n    android:height=\"108dp\"\n"
    out += "    android:viewportWidth=\"108\"\n    android:viewportHeight=\"108\">\n"
    out += paths.joined(separator: "\n") + "\n</vector>\n"
    return out
}

let iconSet = "iosApp/iosApp/Assets.xcassets/AppIcon.appiconset"
try! FileManager.default.createDirectory(atPath: iconSet, withIntermediateDirectories: true)
renderPNG(to: "\(iconSet)/AppIcon-1024.png")
try! vector(monochrome: false).write(toFile: "androidApp/src/main/res/drawable/ic_launcher_foreground.xml", atomically: true, encoding: .utf8)
try! vector(monochrome: true).write(toFile: "androidApp/src/main/res/drawable/ic_launcher_monochrome.xml", atomically: true, encoding: .utf8)
print("Icon written")
